//! Size probe ONLY. Not the wallet contract.
//!
//! Single purpose: force the p256 verification code path to be linked into the
//! WASM so `cargo stylus check` reports a realistic compressed binary size.
//! This answers the feasibility question in CLAUDE.md: does P-256 verification
//! fit inside the 24KB brotli-compressed Stylus limit?
//!
//! The vector below is real, not fabricated: it was generated locally with the
//! p256 crate (fixed test-only scalar, message "PassKeyWallet P-256 size
//! probe") and self-verified before being pasted here. So `verify_hardcoded()`
//! returning true also proves the verify path was not optimised away.

#![cfg_attr(not(any(test, feature = "export-abi")), no_std)]
#![cfg_attr(not(any(test, feature = "export-abi")), no_main)]
extern crate alloc;

// The #[public] macro expands to code using Vec, which is not in the no_std prelude.
use alloc::{vec, vec::Vec};

use p256::ecdsa::{signature::hazmat::PrehashVerifier, Signature, VerifyingKey};
use stylus_sdk::prelude::*;

/// Uncompressed SEC1 public key (0x04 || X || Y).
const PUBKEY_SEC1: [u8; 65] = [
    0x04, 0x2b, 0x6a, 0xc5, 0xfc, 0xa2, 0x54, 0xf6, 0xa6, 0x10, 0x30, 0xd8,
    0xea, 0x0b, 0xb5, 0x2d, 0x95, 0xcd, 0x84, 0x67, 0xb0, 0xc2, 0x3c, 0xd2,
    0x4a, 0x92, 0x96, 0xca, 0x2d, 0x91, 0xb2, 0x76, 0x85, 0x43, 0x09, 0x34,
    0x01, 0x62, 0x43, 0xb0, 0x53, 0x34, 0x48, 0x6d, 0x32, 0x17, 0x9c, 0xbf,
    0x87, 0x4f, 0x3f, 0x68, 0xd3, 0xb9, 0xf1, 0x34, 0x2f, 0x02, 0xee, 0x77,
    0xa5, 0x77, 0xc0, 0x65, 0x1d,
];

/// sha256(b"PassKeyWallet P-256 size probe")
const DIGEST: [u8; 32] = [
    0x5d, 0xc3, 0x01, 0xb0, 0xec, 0x53, 0xfb, 0xcf, 0x6a, 0x1d, 0xfd, 0x95,
    0x39, 0xb3, 0xcc, 0x24, 0xf3, 0x40, 0x18, 0xe3, 0x76, 0x06, 0x33, 0x73,
    0x25, 0x38, 0x23, 0x37, 0xea, 0xda, 0x57, 0x76,
];

/// Fixed-size ECDSA signature (r || s).
const SIG_RS: [u8; 64] = [
    0xa6, 0x9f, 0x07, 0x0b, 0xca, 0x35, 0xc0, 0xf8, 0x7f, 0xee, 0x4a, 0xba,
    0x75, 0x8f, 0x9b, 0xb4, 0x56, 0x3f, 0x66, 0x63, 0xca, 0x8b, 0x97, 0x72,
    0x3e, 0x58, 0x57, 0xcf, 0xc2, 0xfd, 0x8a, 0xb3, 0xd5, 0xd2, 0x28, 0xa6,
    0x08, 0x8a, 0x8a, 0x17, 0x6e, 0x92, 0x0e, 0xaf, 0xcd, 0xd0, 0xc0, 0x62,
    0x08, 0x44, 0x39, 0x13, 0x7b, 0xe6, 0x0c, 0xf6, 0x0f, 0xc3, 0xa9, 0xd5,
    0xe5, 0xf7, 0x4d, 0xeb,
];

sol_storage! {
    #[entrypoint]
    pub struct P256Probe {
    }
}

#[public]
impl P256Probe {
    /// Verifies the hardcoded P-256 signature over the hardcoded digest.
    pub fn verify_hardcoded(&self) -> bool {
        let Ok(vk) = VerifyingKey::from_sec1_bytes(&PUBKEY_SEC1) else {
            return false;
        };
        let Ok(sig) = Signature::from_slice(&SIG_RS) else {
            return false;
        };
        vk.verify_prehash(&DIGEST, &sig).is_ok()
    }
}
